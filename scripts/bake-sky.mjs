// Bakes Midnight Sky and Noonday Sky from src/sky/sun.js into src/sky/baked.ts.
// Run `npm run bake:sky` after changing sun.js, skyTokens.js or a moment.
import { writeFileSync } from 'node:fs';
import { bakeSky } from '../src/sky/skyTokens.js';

const out = new URL('../src/sky/baked.ts', import.meta.url);
const baked = { midnight: bakeSky('midnight'), noonday: bakeSky('noonday') };
writeFileSync(
  out,
  `// Generated by scripts/bake-sky.mjs from src/sky/sun.js. Do not edit.\n` +
    `/* eslint-disable */\n` +
    `export const baked = ${JSON.stringify(baked, null, 2)} as const;\n`
);
